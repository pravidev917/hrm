-- HRM migration V2: client master data, weekly-report client link, notes
--
-- Ships with: the eleven-field client form, the client dropdown on weekly
-- reports, and the employee / administrator notepads.
--
-- Safe to run once against a database created from V1 (or from Hibernate
-- ddl-auto=update in development). Every statement is guarded, so re-running it
-- on a database that already has the changes is a no-op.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Client master data
-- ---------------------------------------------------------------------------
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS client_code             character varying(40);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS vendor                  character varying(150);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS bdm_name                character varying(100);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS position                character varying(150);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS contact_number          character varying(50);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS number_of_positions     integer;
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS salary_offered          numeric(12,2);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS percentage_per_candidate numeric(5,2);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS tax                     numeric(5,2);

-- Client ID is unique per administrator. A plain unique index also allows the
-- legacy rows (client_code IS NULL), which stay valid.
CREATE UNIQUE INDEX IF NOT EXISTS uk_clients_admin_code
    ON public.clients (admin_id, client_code);

CREATE INDEX IF NOT EXISTS ix_clients_admin_status
    ON public.clients (admin_id, status);

-- ---------------------------------------------------------------------------
-- 2. Weekly reports can belong to a client (nullable: older weeks have none)
-- ---------------------------------------------------------------------------
ALTER TABLE public.weekly_reports ADD COLUMN IF NOT EXISTS client_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_weekly_reports_client'
    ) THEN
        ALTER TABLE public.weekly_reports
            ADD CONSTRAINT fk_weekly_reports_client
            FOREIGN KEY (client_id) REFERENCES public.clients (client_id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_weekly_reports_client
    ON public.weekly_reports (client_id);
CREATE INDEX IF NOT EXISTS ix_weekly_reports_admin_week
    ON public.weekly_reports (week_start_date);

-- ---------------------------------------------------------------------------
-- 3. Personal notes (employee notes and the admin notepad)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.notes (
    note_id    bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id bigint,
    admin_id   bigint,
    title      character varying(150),
    content    text NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT notes_pkey PRIMARY KEY (note_id),
    CONSTRAINT fk_notes_employee FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id) ON DELETE CASCADE,
    CONSTRAINT fk_notes_admin FOREIGN KEY (admin_id)
        REFERENCES public.admins (admin_id) ON DELETE CASCADE,
    -- Exactly one owner: an employee's note or an administrator's note.
    CONSTRAINT ck_notes_one_owner CHECK ((employee_id IS NULL) <> (admin_id IS NULL))
);

CREATE INDEX IF NOT EXISTS ix_notes_employee ON public.notes (employee_id);
CREATE INDEX IF NOT EXISTS ix_notes_admin ON public.notes (admin_id);

-- ---------------------------------------------------------------------------
-- 4. Indexes for the dashboard and tracker aggregates
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS ix_daily_reports_admin_date
    ON public.daily_reports (report_date);

COMMIT;
