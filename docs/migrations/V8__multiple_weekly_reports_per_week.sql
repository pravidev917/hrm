-- V8: an employee may file more than one weekly report for the same week.
--
-- Weekly reports used to be unique per employee and week, enforced both in the service
-- (three duplicate checks, now removed) and by two unique constraints on the table. Both
-- constraints have to go, otherwise a second report for the same week fails in the
-- database even though the application now allows it.
--
-- Every consumer sums the rows it reads (reporting totals and budgets, the performance
-- tracker, the employee dashboard), so several reports add up instead of replacing each
-- other.

BEGIN;

-- One constraint came from the baseline schema, the other was generated by Hibernate from
-- the entity's @UniqueConstraint, which has now been deleted.
ALTER TABLE public.weekly_reports
    DROP CONSTRAINT IF EXISTS uk_weekly_reports_employee_id_week_end_date_week_start_date;

ALTER TABLE public.weekly_reports
    DROP CONSTRAINT IF EXISTS ukdkwc5to6d2ryh4isbkt96kytp;

DROP INDEX IF EXISTS public.uk_weekly_reports_employee_id_week_end_date_week_start_date;
DROP INDEX IF EXISTS public.ukdkwc5to6d2ryh4isbkt96kytp;

-- Lookups by employee and week now mean "find all of them", so index the pair.
CREATE INDEX IF NOT EXISTS ix_weekly_reports_employee_week
    ON public.weekly_reports (employee_id, week_start_date);

COMMIT;
