-- V4: location-based office attendance and administrator-approved WFH.
--
-- Adds, without touching existing rows:
--   1. office_locations  one office + timezone + radius per company (shared by
--                        every administrator of that company)
--   2. wfh_requests      employee WFH requests and their review trail
--   3. audit_logs        append-only trail for settings changes and WFH decisions
--   4. attendance        work mode + verification evidence + approved-WFH link
--
-- Existing attendance rows keep status PRESENT/ABSENT and a NULL work_mode,
-- which the UI reads as "not recorded" rather than inventing a mode. No table is
-- rewritten or dropped. Safe to re-run: every statement is guarded.

BEGIN;

CREATE TABLE IF NOT EXISTS public.office_locations (
    office_location_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id bigint NOT NULL,
    office_name character varying(150) NOT NULL,
    latitude numeric(9,6) NOT NULL,
    longitude numeric(9,6) NOT NULL,
    radius_meters integer NOT NULL,
    timezone character varying(64) NOT NULL,
    updated_by_admin_id bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT office_locations_pkey PRIMARY KEY (office_location_id),
    CONSTRAINT uk_office_locations_company UNIQUE (company_id),
    CONSTRAINT ck_office_locations_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_office_locations_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_office_locations_radius CHECK (radius_meters BETWEEN 10 AND 10000)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_office_locations_company') THEN
        ALTER TABLE public.office_locations
            ADD CONSTRAINT fk_office_locations_company
            FOREIGN KEY (company_id) REFERENCES public.companies (company_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_office_locations_updated_by') THEN
        ALTER TABLE public.office_locations
            ADD CONSTRAINT fk_office_locations_updated_by
            FOREIGN KEY (updated_by_admin_id) REFERENCES public.admins (admin_id);
    END IF;
END $$;

COMMENT ON TABLE public.office_locations IS
    'One physical office per company, used to verify office attendance.';

CREATE TABLE IF NOT EXISTS public.wfh_requests (
    wfh_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id bigint NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    reason text NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by_admin_id bigint,
    admin_comment text,
    reviewed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT wfh_requests_pkey PRIMARY KEY (wfh_id),
    CONSTRAINT ck_wfh_requests_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_wfh_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_wfh_requests_employee') THEN
        ALTER TABLE public.wfh_requests
            ADD CONSTRAINT fk_wfh_requests_employee
            FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_wfh_requests_reviewed_by') THEN
        ALTER TABLE public.wfh_requests
            ADD CONSTRAINT fk_wfh_requests_reviewed_by
            FOREIGN KEY (reviewed_by_admin_id) REFERENCES public.admins (admin_id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_wfh_requests_employee
    ON public.wfh_requests (employee_id);
CREATE INDEX IF NOT EXISTS idx_wfh_requests_status_dates
    ON public.wfh_requests (status, start_date, end_date);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    audit_log_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id bigint NOT NULL,
    actor_type character varying(20) NOT NULL,
    actor_id bigint,
    actor_name character varying(150),
    action character varying(60) NOT NULL,
    entity_type character varying(40),
    entity_id bigint,
    details text,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT audit_logs_pkey PRIMARY KEY (audit_log_id)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_audit_logs_company') THEN
        ALTER TABLE public.audit_logs
            ADD CONSTRAINT fk_audit_logs_company
            FOREIGN KEY (company_id) REFERENCES public.companies (company_id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_audit_logs_company_created
    ON public.audit_logs (company_id, created_at);

ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS work_mode character varying(20);
ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS distance_meters numeric(8,2);
ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS accuracy_meters numeric(8,2);
ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS location_captured_at timestamp(6) without time zone;
ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS marked_at timestamp(6) without time zone;
ALTER TABLE public.attendance
    ADD COLUMN IF NOT EXISTS wfh_request_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_attendance_work_mode') THEN
        ALTER TABLE public.attendance
            ADD CONSTRAINT ck_attendance_work_mode
            CHECK (work_mode IS NULL OR work_mode IN ('OFFICE', 'WFH'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_attendance_wfh_request') THEN
        ALTER TABLE public.attendance
            ADD CONSTRAINT fk_attendance_wfh_request
            FOREIGN KEY (wfh_request_id) REFERENCES public.wfh_requests (wfh_id)
            ON DELETE SET NULL;
    END IF;
END $$;

COMMENT ON COLUMN public.attendance.work_mode IS
    'OFFICE or WFH for server-verified PRESENT records; NULL for ABSENT and legacy rows.';
COMMENT ON COLUMN public.attendance.distance_meters IS
    'Verified distance from the office (metres). Precise coordinates are deliberately not stored.';

COMMIT;
