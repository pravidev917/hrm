-- V5: reporting, sourcing platforms, candidate tracking and salary history.
--
-- Adds, without rewriting or dropping existing rows:
--   1. sourcing_platforms         company-managed list of sourcing platforms
--   2. daily_report_platform_counts  per-platform sourced-profile counts for a
--                                    daily report (more than one platform per report)
--   3. daily_reports.sourcing_platform  legacy/single-platform fallback
--   4. feedback.sourcing_platform / sourced_date  candidate tracking fields
--   5. clients.budget_per_candidate   explicit per-candidate client budget
--   6. employee_salary_history       month-effective salary used by salary x 3 targets
--
-- Existing daily reports and candidates keep NULL platform values, which the UI
-- and the reporting service surface as "Unknown" rather than inventing a value.
-- Safe to re-run: every statement is guarded.

BEGIN;

-- ---- company-managed sourcing platforms -----------------------------------

CREATE TABLE IF NOT EXISTS public.sourcing_platforms (
    sourcing_platform_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id bigint NOT NULL,
    name character varying(80) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT sourcing_platforms_pkey PRIMARY KEY (sourcing_platform_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sourcing_platforms_company_name
    ON public.sourcing_platforms (company_id, lower(name));

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_sourcing_platforms_company') THEN
        ALTER TABLE public.sourcing_platforms
            ADD CONSTRAINT fk_sourcing_platforms_company
            FOREIGN KEY (company_id) REFERENCES public.companies (company_id);
    END IF;
END $$;

INSERT INTO public.sourcing_platforms
    (company_id, name, active, sort_order, created_at, updated_at)
SELECT c.company_id, defaults.name, true, defaults.sort_order, now(), now()
FROM public.companies c
CROSS JOIN (
    VALUES
        ('LinkedIn', 10),
        ('Naukri', 20),
        ('Indeed', 30),
        ('Referral', 40),
        ('Company Website', 50),
        ('Other', 60)
) AS defaults(name, sort_order)
WHERE NOT EXISTS (
    SELECT 1 FROM public.sourcing_platforms p
    WHERE p.company_id = c.company_id
      AND lower(p.name) = lower(defaults.name)
);

-- ---- daily report platform counts ----------------------------------------

ALTER TABLE public.daily_reports
    ADD COLUMN IF NOT EXISTS sourcing_platform character varying(80);

CREATE TABLE IF NOT EXISTS public.daily_report_platform_counts (
    daily_report_platform_count_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    daily_report_id bigint NOT NULL,
    platform character varying(80) NOT NULL,
    profile_count integer NOT NULL,
    CONSTRAINT daily_report_platform_counts_pkey PRIMARY KEY (daily_report_platform_count_id),
    CONSTRAINT ck_daily_report_platform_counts_non_negative CHECK (profile_count >= 0),
    CONSTRAINT uk_daily_report_platform_counts UNIQUE (daily_report_id, platform)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_daily_report_platform_counts_report') THEN
        ALTER TABLE public.daily_report_platform_counts
            ADD CONSTRAINT fk_daily_report_platform_counts_report
            FOREIGN KEY (daily_report_id) REFERENCES public.daily_reports (daily_report_id)
            ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_daily_report_platform_counts_platform
    ON public.daily_report_platform_counts (platform);

-- ---- candidate tracking fields -------------------------------------------

ALTER TABLE public.feedback
    ADD COLUMN IF NOT EXISTS sourcing_platform character varying(80);
ALTER TABLE public.feedback
    ADD COLUMN IF NOT EXISTS sourced_date date;

CREATE INDEX IF NOT EXISTS idx_feedback_employee_sourced_date
    ON public.feedback (employee_id, sourced_date);
CREATE INDEX IF NOT EXISTS idx_feedback_employee_platform
    ON public.feedback (employee_id, sourcing_platform);

-- ---- client budget --------------------------------------------------------

ALTER TABLE public.clients
    ADD COLUMN IF NOT EXISTS budget_per_candidate numeric(12,2);

-- One-time derivation for existing clients: the placement-fee budget implied by
-- the stored salary offered and percentage per candidate. Administrators can
-- override the value through the client form afterwards.
UPDATE public.clients
SET budget_per_candidate = ROUND(salary_offered * percentage_per_candidate / 100.0, 2)
WHERE budget_per_candidate IS NULL
  AND salary_offered IS NOT NULL
  AND percentage_per_candidate IS NOT NULL;

-- ---- month-effective salary history --------------------------------------

CREATE TABLE IF NOT EXISTS public.employee_salary_history (
    employee_salary_history_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id bigint NOT NULL,
    effective_month date NOT NULL,
    salary numeric(12,2),
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT employee_salary_history_pkey PRIMARY KEY (employee_salary_history_id),
    CONSTRAINT uk_employee_salary_history_month UNIQUE (employee_id, effective_month),
    CONSTRAINT ck_employee_salary_history_month CHECK (date_part('day', effective_month) = 1)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employee_salary_history_employee') THEN
        ALTER TABLE public.employee_salary_history
            ADD CONSTRAINT fk_employee_salary_history_employee
            FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id)
            ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_employee_salary_history_employee_month
    ON public.employee_salary_history (employee_id, effective_month DESC);

-- Existing salaries become effective from the month the employee record was
-- created (or January 1970 when no creation timestamp was stored). Later salary
-- changes add new rows, so historical monthly targets are not rewritten.
INSERT INTO public.employee_salary_history
    (employee_id, effective_month, salary, created_at)
SELECT e.employee_id,
       date_trunc('month', COALESCE(e.created_at, TIMESTAMP '1970-01-01'))::date,
       e.salary,
       now()
FROM public.employees e
WHERE e.salary IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM public.employee_salary_history h
      WHERE h.employee_id = e.employee_id
  );

CREATE INDEX IF NOT EXISTS idx_weekly_reports_client_week
    ON public.weekly_reports (client_id, week_start_date);

COMMIT;
