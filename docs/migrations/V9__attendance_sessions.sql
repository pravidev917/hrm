-- V9: login/logout attendance sessions.
--
-- What this adds
--   1. attendance_sessions  one row per Log In -> Log Out pair, with server timestamps
--   2. indexes + constraints that make "one active session per employee" a database rule
--
-- What this deliberately does NOT do
--   * the attendance table keeps its rows: it stays the daily record (PRESENT/ABSENT)
--     and every historical row, report and calendar entry keeps working.
--   * no uniqueness on attendance_sessions (employee_id, attendance_date): an employee
--     can log in and out many times in one day and every session is stored.
--   * no back-filling of login times. Sessions start with real logins; days before this
--     migration keep their attendance row and show "no login record" instead of invented
--     timestamps.
--
-- Timezone: timestamps are stored as PostgreSQL `timestamp with time zone` (UTC instants).
-- Asia/Kolkata (or the company's office timezone) is only used to decide which
-- attendance_date a session belongs to and how times are displayed.

BEGIN;

CREATE TABLE IF NOT EXISTS public.attendance_sessions (
    session_id       bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id      bigint NOT NULL,
    attendance_date  date NOT NULL,
    login_at         timestamp(6) with time zone NOT NULL,
    logout_at        timestamp(6) with time zone,
    duration_seconds bigint,
    status           character varying(20) NOT NULL,
    closed_by        character varying(20),
    created_at       timestamp(6) with time zone NOT NULL,
    updated_at       timestamp(6) with time zone NOT NULL,
    CONSTRAINT attendance_sessions_pkey PRIMARY KEY (session_id),
    CONSTRAINT fk_attendance_sessions_employee
        FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_attendance_sessions_status') THEN
        ALTER TABLE public.attendance_sessions
            ADD CONSTRAINT ck_attendance_sessions_status
            CHECK (status IN ('ACTIVE', 'CLOSED', 'INCOMPLETE'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_attendance_sessions_closed_by') THEN
        ALTER TABLE public.attendance_sessions
            ADD CONSTRAINT ck_attendance_sessions_closed_by
            CHECK (closed_by IS NULL OR closed_by IN ('EMPLOYEE', 'SYSTEM'));
    END IF;

    -- A session can never end before it started, and a stored duration is never negative.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_attendance_sessions_order') THEN
        ALTER TABLE public.attendance_sessions
            ADD CONSTRAINT ck_attendance_sessions_order
            CHECK (logout_at IS NULL OR logout_at >= login_at);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_attendance_sessions_duration') THEN
        ALTER TABLE public.attendance_sessions
            ADD CONSTRAINT ck_attendance_sessions_duration
            CHECK (duration_seconds IS NULL OR duration_seconds >= 0);
    END IF;
END $$;

-- One open session per employee, enforced by the database itself. Two simultaneous
-- Log In requests cannot both succeed, even if the application-level check races.
CREATE UNIQUE INDEX IF NOT EXISTS uk_attendance_sessions_one_active
    ON public.attendance_sessions (employee_id)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS ix_attendance_sessions_employee_date
    ON public.attendance_sessions (employee_id, attendance_date);

CREATE INDEX IF NOT EXISTS ix_attendance_sessions_date
    ON public.attendance_sessions (attendance_date);

CREATE INDEX IF NOT EXISTS ix_attendance_sessions_active_date
    ON public.attendance_sessions (status, attendance_date);

COMMENT ON TABLE public.attendance_sessions IS
    'One row per employee Log In / Log Out pair. TIMESTAMPTZ, written from server clock only.';
COMMENT ON COLUMN public.attendance_sessions.attendance_date IS
    'Company-local date of the login; a session that crosses midnight stays on its login date.';
COMMENT ON COLUMN public.attendance_sessions.duration_seconds IS
    'Whole seconds between login_at and logout_at, computed by the server at logout.';
COMMENT ON COLUMN public.attendance_sessions.status IS
    'ACTIVE (open), CLOSED (logged out) or INCOMPLETE (left open on a previous day).';

COMMIT;
