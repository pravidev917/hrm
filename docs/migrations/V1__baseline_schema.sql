ALTER TABLE public.daily_reports ADD CONSTRAINT fk_daily_reports_client_id FOREIGN KEY (client_id) REFERENCES public.clients (client_id);
ALTER TABLE public.daily_reports ADD CONSTRAINT fk_daily_reports_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
ALTER TABLE public.employees ADD CONSTRAINT fk_employees_admin_id FOREIGN KEY (admin_id) REFERENCES public.admins (admin_id);
ALTER TABLE public.feedback ADD CONSTRAINT fk_feedback_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
ALTER TABLE public.followups ADD CONSTRAINT fk_followups_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
ALTER TABLE public.holidays ADD CONSTRAINT fk_holidays_admin_id FOREIGN KEY (admin_id) REFERENCES public.admins (admin_id);
ALTER TABLE public.leave_management ADD CONSTRAINT fk_leave_management_admin_id FOREIGN KEY (admin_id) REFERENCES public.admins (admin_id);
ALTER TABLE public.leave_management ADD CONSTRAINT fk_leave_management_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
ALTER TABLE public.performance ADD CONSTRAINT fk_performance_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);
ALTER TABLE public.weekly_reports ADD CONSTRAINT fk_weekly_reports_employee_id FOREIGN KEY (employee_id) REFERENCES public.employees (employee_id);

COMMIT;
