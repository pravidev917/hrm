-- HRM baseline schema (V1)
-- Generated from the JPA entity mappings and verified by booting the
-- application with DB_DDL_AUTO=validate against a scratch database.
-- Apply once to an EMPTY public schema, then keep DB_DDL_AUTO=validate.

BEGIN;

-- Refuse to run against a schema that already holds application objects.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type IN ('BASE TABLE', 'VIEW')
    ) THEN
        RAISE EXCEPTION 'public schema is not empty - baseline aborted';
    END IF;
END $$;

CREATE TABLE public.admins (
    admin_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    admin_name character varying(100) NOT NULL,
    contact_details character varying(50),
    created_at timestamp(6) without time zone,
    email character varying(150) NOT NULL,
    password character varying(255) NOT NULL,
    role_access_level character varying(50) NOT NULL,
    status character varying(20) NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT admins_pkey PRIMARY KEY (admin_id),
    CONSTRAINT uk_admins_email UNIQUE (email)
);

CREATE TABLE public.employees (
    employee_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    contact character varying(50),
    employee_name character varying(100) NOT NULL,
    role character varying(50) NOT NULL,
    admin_id bigint NOT NULL,
    account_status character varying(20) NOT NULL,
    created_at timestamp(6) without time zone,
    email character varying(150) NOT NULL,
    password character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone,
    date_of_birth date,
    joining_date date,
    department character varying(100),
    employee_code character varying(40),
    salary numeric(12,2),
    CONSTRAINT employees_pkey PRIMARY KEY (employee_id),
    CONSTRAINT uk_employees_employee_code UNIQUE (employee_code),
    CONSTRAINT uk_employees_email UNIQUE (email)
);

CREATE TABLE public.attendance (
    attendance_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    attendance_date date NOT NULL,
    status character varying(20) NOT NULL,
    employee_id bigint NOT NULL,
    CONSTRAINT attendance_pkey PRIMARY KEY (attendance_id),
    CONSTRAINT uk_attendance_attendance_date_employee_id UNIQUE (attendance_date, employee_id)
);

CREATE TABLE public.clients (
    client_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    client_name character varying(150) NOT NULL,
    hr_contact_details character varying(150),
    hr_name character varying(100),
    interviews_conducted integer,
    joining_details text,
    profiles_submitted integer,
    selected_candidates integer,
    admin_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    CONSTRAINT clients_pkey PRIMARY KEY (client_id)
);

CREATE TABLE public.daily_reports (
    daily_report_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    connected_count integer NOT NULL,
    profiles_submitted integer NOT NULL,
    report_date date NOT NULL,
    employee_id bigint NOT NULL,
    client_id bigint NOT NULL,
    candidates_sourced integer DEFAULT 0 NOT NULL,
    candidates_contacted integer DEFAULT 0 NOT NULL,
    remarks text,
    CONSTRAINT daily_reports_pkey PRIMARY KEY (daily_report_id)
);

CREATE TABLE public.feedback (
    feedback_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    candidate_name character varying(100) NOT NULL,
    client character varying(150),
    comments text,
    feedback_received character varying(30) NOT NULL,
    employee_id bigint NOT NULL,
    candidate_email character varying(150),
    client_name character varying(150),
    contact_number character varying(30),
    current_company character varying(150),
    current_ctc numeric(12,2),
    current_designation character varying(100),
    current_location character varying(100),
    expected_ctc numeric(12,2),
    google_feedback_given boolean,
    hr_name character varying(100),
    interview_attended boolean,
    interview_scheduled boolean,
    interview_scheduled_date date,
    notice_period_days integer,
    preferred_location character varying(100),
    status character varying(30),
    CONSTRAINT feedback_pkey PRIMARY KEY (feedback_id)
);

CREATE TABLE public.followups (
    followup_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    candidate_name character varying(100) NOT NULL,
    client character varying(150),
    join_date date,
    joining_status character varying(30),
    reason text,
    employee_id bigint NOT NULL,
    CONSTRAINT followups_pkey PRIMARY KEY (followup_id)
);

CREATE TABLE public.holidays (
    holiday_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) without time zone,
    description character varying(255),
    holiday_date date NOT NULL,
    holiday_name character varying(120) NOT NULL,
    admin_id bigint NOT NULL,
    CONSTRAINT holidays_pkey PRIMARY KEY (holiday_id)
);

CREATE TABLE public.leave_management (
    leave_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    leave_date date,
    number_of_days numeric(5,2) NOT NULL,
    reason text,
    status character varying(20) NOT NULL,
    leave_type character varying(50) NOT NULL,
    admin_id bigint,
    employee_id bigint NOT NULL,
    admin_remarks text,
    end_date date NOT NULL,
    half_day_period character varying(20),
    reviewed_at timestamp(6) without time zone,
    start_date date NOT NULL,
    CONSTRAINT leave_management_pkey PRIMARY KEY (leave_id)
);

CREATE TABLE public.performance (
    performance_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    daily_performance text,
    overall_rating numeric(3,2),
    weekly_performance text,
    employee_id bigint NOT NULL,
    CONSTRAINT performance_pkey PRIMARY KEY (performance_id)
);

CREATE TABLE public.vw_monthly_performance (
    dashboard_id bigint NOT NULL,
    employee_id bigint,
    month integer,
    overall_rating numeric(3,2),
    total_interviews_scheduled bigint,
    total_joined bigint,
    total_profiles_submitted bigint,
    total_revenue numeric(12,2),
    total_selections bigint,
    year integer,
    CONSTRAINT vw_monthly_performance_pkey PRIMARY KEY (dashboard_id)
);

CREATE TABLE public.weekly_reports (
    weekly_report_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    final_selections integer NOT NULL,
    interviews_scheduled integer NOT NULL,
    joined integer NOT NULL,
    profiles_submitted integer NOT NULL,
    revenue_generated numeric(12,2),
    week_number integer NOT NULL,
    employee_id bigint NOT NULL,
    week_end_date date NOT NULL,
    week_start_date date NOT NULL,
    CONSTRAINT weekly_reports_pkey PRIMARY KEY (weekly_report_id),
    CONSTRAINT uk_weekly_reports_employee_id_week_end_date_week_start_date UNIQUE (employee_id, week_end_date, week_start_date)
);

-- The entity also declares employees.contact unique (sign-in identifier);
-- Hibernate 'update' never added it, so the baseline creates it explicitly.
ALTER TABLE public.employees ADD CONSTRAINT uk_employees_contact UNIQUE (contact);

